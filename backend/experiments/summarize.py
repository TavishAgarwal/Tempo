"""Render docs/results-summary.md from the CSV tables in results/ (from saved run records)."""

from __future__ import annotations

import csv
import logging
from pathlib import Path

from taqpso.config import DATA_DIR
from taqpso.store.results import git_info

log = logging.getLogger("summarize")
TITLES = {
    "e1": "E1 correctness (static)",
    "e2": "E2 QPSO vs classical (equal wall-clock budget; A12 = P(QPSO better); Holm-corrected p)",
    "e2_large": "E2 at scale, n = 200 and n = 500 (Phase 8; same protocol as E2)",
    "e3": "E3 traffic value (static vs TD planning, realised under the simulator)",
    "e4": "E4 incident recovery",
    "e5": "E5 scaling",
}


def fmt(v: str) -> str:
    try:
        f = float(v)
    except ValueError:
        return v or "–"
    return f"{f:.4g}"


def md_table(path: Path) -> str:
    with path.open() as fh:
        rows = list(csv.reader(fh))
    if not rows:
        return ""
    head, body = rows[0], rows[1:]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in body]
    return "\n".join(out)


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    root = DATA_DIR.parent / "results"
    g = git_info()
    parts = [
        "# Results summary (generated from saved run records)\n",
        f"Generated by `python -m experiments.summarize` at commit "
        f"`{g.get('commit', '?')[:10]}`"
        f"{' (dirty)' if g.get('dirty') else ''}. All numbers come from `results/runs/*.json` "
        "(instance hash, resolved config, seed, solver, budget, commit). Delhi instances use the "
        "*calibrated time-of-day profile (synthetic)* (TomTom-2025 anchored, see "
        "`calibration-notes.md`); each solver is scored by the edge-level simulator. "
        "Parallel worker processes share one machine, so wall-clock effects carry contention "
        "noise (latency gates are measured separately, e4/latency.csv). Tuning used "
        "disjoint instances (`delhi_tune1/2/3`); E2 and E2-at-scale apply `configs/tuned.yaml`, "
        "while E1 and E3–E5 were run before the driver applied it (default parameters). "
        "Losses are reported as well as wins.\n",
    ]
    for key, title in TITLES.items():
        d = root / key
        if not d.exists():
            continue
        parts.append(f"\n## {title}\n")
        for csvf in sorted(d.glob("*.csv")):
            if csvf.name == "runs.csv":
                continue
            parts.append(f"\n`{key}/{csvf.name}`\n\n" + md_table(csvf) + "\n")
    for f in sorted(root.glob("poryos_*.json")):
        import json

        rows = json.loads(f.read_text())
        if not rows:
            continue
        parts.append(f"\n## {f.stem}\n\n| " + " | ".join(rows[0]) + " |\n|" + "---|" * len(rows[0]))
        parts += ["| " + " | ".join(fmt(str(v)) for v in r.values()) + " |" for r in rows]
        parts.append("")
    out = DATA_DIR.parent / "docs" / "results-summary.md"
    out.write_text("\n".join(parts))
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
